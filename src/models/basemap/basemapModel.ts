import { z } from 'zod';
import { PersistedBasemapSchema } from '@map-colonies/app-shared';
import { FieldCategory } from '../common/decorators/fieldConfig/fieldConfig.decorator';
import { createAnnotatedZodObject, registerAnnotatedZodObject, ZodFieldAnnotations } from '../common/zod';
import { BASEMAP_LAYER_TYPE, BASEMAP_THUMBNAIL_TYPE } from './basemapTypes';

/**
 * Registered under the name 'Basemap' - the real, primary entity, built from app-shared's
 * `PersistedBasemapSchema` (= `BasemapWriteInputSchema` + a server-assigned `id`), not from the write
 * schema alone. `BasemapWriteInputSchema` remains exactly what it's good at - validating API call
 * parameters in `basemap-management` - and is no longer what mc-models' GraphQL generation is built
 * around; `id` is `isAutoGenerated` so it's excluded from the derived `BasemapInput`.
 *
 * `layers` is overridden to `z.array(z.unknown())`: `PersistedBasemapSchema`'s own `layers` is an array
 * of the INPUT `BasemapLayerInput` shape, not the output `BasemapLayerOutput` shape this entity actually
 * has - same reasoning as `basemapLayerModel.ts`'s own `source` override. The real element type is fully
 * described by the `tsType`/`complexType` annotation (`BASEMAP_LAYER_TYPE`, pointing at the entity-shaped
 * 'BasemapLayer'), not by this zod validator.
 *
 * Known gap, deliberately out of scope here: `catalog-web-app-bff`'s existing hand-written
 * `CreateBasemapInput`/`UpdateBasemapInput` additionally flatten `thumbnail` into
 * `thumbnailBase64`/`thumbnailContentType` upload fields and split create vs. update essentiality -
 * an upload-semantics concern independent of the entity/union work done here. The derived `BasemapInput`
 * below is a reasonable single shape in the meantime, not yet a drop-in replacement for those two.
 */
const basemapSchema = PersistedBasemapSchema.extend({ layers: z.array(z.unknown()) });

type PersistedBasemapShape = typeof basemapSchema.shape;

const persistedBasemapAnnotations: ZodFieldAnnotations<PersistedBasemapShape> = {
  id: {
    fieldConfig: { category: FieldCategory.MAIN, isRequired: true, isAutoGenerated: true },
    graphql: { nullable: false },
  },
  name: {
    fieldConfig: {
      category: FieldCategory.MAIN,
      isRequired: true,
      isFilterable: true,
      isSortable: true,
      isCreateEssential: true,
      isUpdateEssential: true,
    },
    graphql: { nullable: false },
  },
  thumbnail: {
    fieldConfig: {
      category: FieldCategory.MAIN,
      isRequired: true,
      isCreateEssential: true,
      isUpdateEssential: true,
      complexType: BASEMAP_THUMBNAIL_TYPE,
    },
    graphql: { nullable: false },
    tsType: BASEMAP_THUMBNAIL_TYPE,
  },
  isCurrent: {
    fieldConfig: { category: FieldCategory.MAIN, isRequired: true, isFilterable: true, isCreateEssential: true, isUpdateEssential: true },
    graphql: { nullable: false },
  },
  isForPreview: {
    fieldConfig: { category: FieldCategory.MAIN, isRequired: true, isFilterable: true, isCreateEssential: true, isUpdateEssential: true },
    graphql: { nullable: false },
  },
  layers: {
    fieldConfig: {
      category: FieldCategory.MAIN,
      isRequired: true,
      isCreateEssential: true,
      isUpdateEssential: true,
      complexType: BASEMAP_LAYER_TYPE,
    },
    graphql: { nullable: false },
    tsType: BASEMAP_LAYER_TYPE,
  },
};

/**
 * Extends `@map-colonies/app-shared`'s `PersistedBasemapSchema` with generation metadata, so
 * `code-generator` can produce the `catalog-web-app-bff` GraphQL input/object classes for it the
 * same way it already does for the decorator-based layerMetadata models.
 *
 * `registerAnnotatedZodObject` bridges it into `getFieldConfigClassInfo()`/`getGraphQLClassMapping()`
 * - the same functions `@fieldConfigClass()`/`@graphqlClass()` populate - so `code-generator` keeps
 * calling those two functions only, unaware this model is zod-backed rather than class-decorated.
 */
export const basemapModel = registerAnnotatedZodObject(createAnnotatedZodObject(basemapSchema, persistedBasemapAnnotations, 'Basemap'));
