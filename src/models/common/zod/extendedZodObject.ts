import { z } from 'zod';
import { getFieldConfigClassInfo } from '../decorators/fieldConfig/classFieldConfig.decorator';
import { IFieldConfigInfo, IPropFieldConfigInfo } from '../decorators/fieldConfig/fieldConfig.decorator';
import { IPropGraphQLMapping } from '../interfaces/propGraphQLMapping.interface';
import { inferZodTsType } from './inferZodTsType';
import { IZodFieldAnnotation, ZodFieldAnnotations } from './types';

/**
 * Wraps a zod object schema together with a parallel map of per-field annotations
 * (the zod-schema equivalent of the `@fieldConfig`/`@graphql`/`@tsTypes` property decorators),
 * and exposes `getFieldConfigs()`/`getGraphQLMappings()` so the model can be generated by
 * `code-generator`, the same way the decorator-based model classes are.
 *
 * Composition (rather than subclassing `z.ZodObject`) is deliberate: zod v3's `ZodObject.extend()`
 * always returns a plain `ZodObject`, so a subclass would silently lose its extra methods the
 * moment it was `.extend()`-ed. `AnnotatedZodObject#extend` below re-wraps the result instead.
 */
export interface IAnnotatedZodObjectOptions {
  /** Skip generating this model's `${name}Input` class - e.g. a union branch with no legitimate input shape of its own. */
  skipInputType?: boolean;
  /** Skip generating this model's `${name}` ObjectType (and `${name}Resolver`) - e.g. a parameters-only shape. */
  skipObjectType?: boolean;
}

export class AnnotatedZodObject<Shape extends z.ZodRawShape> {
  public readonly skipInputType?: boolean;
  public readonly skipObjectType?: boolean;

  public constructor(
    public readonly schema: z.ZodObject<Shape>,
    private readonly annotations: ZodFieldAnnotations<Shape> = {},
    public readonly name: string = 'AnnotatedZodObject',
    options: IAnnotatedZodObjectOptions = {}
  ) {
    this.skipInputType = options.skipInputType;
    this.skipObjectType = options.skipObjectType;
  }

  public extend<Augmentation extends z.ZodRawShape>(
    augmentationShape: Augmentation,
    augmentationAnnotations: ZodFieldAnnotations<Augmentation> = {},
    name?: string,
    options?: IAnnotatedZodObjectOptions
  ): AnnotatedZodObject<Shape & Augmentation> {
    const extendedSchema = this.schema.extend(augmentationShape) as unknown as z.ZodObject<Shape & Augmentation>;
    const mergedAnnotations = {
      ...this.annotations,
      ...augmentationAnnotations,
    } as ZodFieldAnnotations<Shape & Augmentation>;
    return new AnnotatedZodObject<Shape & Augmentation>(extendedSchema, mergedAnnotations, name ?? this.name, {
      skipInputType: options?.skipInputType ?? this.skipInputType,
      skipObjectType: options?.skipObjectType ?? this.skipObjectType,
    });
  }

  public parse(data: unknown): z.infer<z.ZodObject<Shape>> {
    return this.schema.parse(data);
  }

  public safeParse(data: unknown): z.SafeParseReturnType<unknown, z.infer<z.ZodObject<Shape>>> {
    return this.schema.safeParse(data);
  }

  public getAnnotation(prop: keyof Shape): IZodFieldAnnotation | undefined {
    return this.annotations[prop];
  }

  public getFieldConfigs(): IPropFieldConfigInfo[] {
    const ret: IPropFieldConfigInfo[] = [];
    for (const prop of Object.keys(this.schema.shape)) {
      const fieldConfig = this.annotations[prop as keyof Shape]?.fieldConfig;
      if (fieldConfig === undefined) {
        continue;
      }
      ret.push(this.toFieldConfigEntry(prop, fieldConfig));
    }
    return ret;
  }

  public getGraphQLMappings(fields?: string[]): IPropGraphQLMapping[] {
    const shape = this.schema.shape;
    const props = fields ?? Object.keys(shape);
    const ret: IPropGraphQLMapping[] = [];

    props.forEach((prop) => {
      const annotation = this.annotations[prop as keyof Shape];
      const mappingType = annotation?.tsType ?? inferZodTsType(shape[prop as keyof Shape] as z.ZodTypeAny);
      if (annotation?.graphql === undefined || mappingType === undefined) {
        return;
      }
      ret.push({
        prop,
        ...annotation.graphql,
        mappingType,
        isAutoGenerated: annotation.fieldConfig?.isAutoGenerated,
        isLifecycleEnvolved: annotation.fieldConfig?.isLifecycleEnvolved,
      });
    });

    return ret;
  }

  private toFieldConfigEntry(prop: string, fieldConfig: IFieldConfigInfo): IPropFieldConfigInfo {
    const entry: IPropFieldConfigInfo = { prop, ...fieldConfig };
    if (fieldConfig.complexType) {
      // mirrors the class-based models' own getFieldConfigs() overrides (e.g. PycswLayerCatalogRecord),
      // which resolve a `complexType`-annotated field's nested class info the same way.
      entry.subFields = getFieldConfigClassInfo(fieldConfig.complexType.value);
    }
    return entry;
  }
}

export function createAnnotatedZodObject<Shape extends z.ZodRawShape>(
  schema: z.ZodObject<Shape>,
  annotations: ZodFieldAnnotations<Shape> = {},
  name?: string,
  options?: IAnnotatedZodObjectOptions
): AnnotatedZodObject<Shape> {
  return new AnnotatedZodObject(schema, annotations, name, options);
}
